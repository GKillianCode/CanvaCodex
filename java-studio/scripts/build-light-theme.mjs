import fs from "node:fs";
import postcss from "postcss";
import { lightUIColor } from "../src/appearancePalette.js";
const url = new URL("../src/style.css", import.meta.url);
const source = postcss.parse(fs.readFileSync(url, "utf8"));
const output = postcss.root();
const scope = ':root[data-appearance="light"]';
function convert(value, role) {
  return value
    .replace(/#[\da-f]{3,8}\b/gi, (c) => lightUIColor(c, role))
    .replace(/\bwhite\b/gi, role === "ink" ? "#25382e" : "#ffffff")
    .replace(/\bblack\b/gi, role === "surface" ? "#f7faf8" : "#1b2d23");
}
function walk(input, target) {
  for (const node of input.nodes || []) {
    if (node.type === "atrule") {
      if (!["media", "supports", "layer", "container"].includes(node.name))
        continue;
      const at = postcss.atRule({ name: node.name, params: node.params });
      walk(node, at);
      if (at.nodes?.length) target.append(at);
      continue;
    }
    if (node.type !== "rule") continue;
    // Preview colors represent project data, not application appearance.
    if (
      /(?:swatch|theme-preview|shape-preview|palette-preview|component-preview|audience-surface)/.test(
        node.selector,
      )
    )
      continue;
    const rule = postcss.rule({
      selector: node.selectors
        .map((s) =>
          s.includes(":root") ? s.replace(":root", scope) : scope + " " + s,
        )
        .join(","),
    });
    for (const decl of node.nodes || []) {
      if (decl.type !== "decl" || decl.prop.startsWith("--")) continue;
      const role = /^(?:background|background-color|background-image)$/.test(
        decl.prop,
      )
        ? "surface"
        : /^(?:color|caret-color|fill|stroke|text-decoration-color)$/.test(
              decl.prop,
            )
          ? "ink"
          : /^(?:border(?:-.+)?|outline(?:-.+)?)$/.test(decl.prop)
            ? "line"
            : null;
      if (!role) continue;
      if (role === "surface" && /backdrop/.test(node.selector)) continue;
      const value = convert(decl.value, role);
      rule.append(decl.clone({ value }));
    }
    if (rule.nodes?.length) target.append(rule);
  }
}
walk(source, output);
fs.writeFileSync(
  new URL("../src/light.generated.css", import.meta.url),
  "/* Generated by npm run theme:build from style.css. UI only. */\n" +
    output.toString() +
    "\n",
);
